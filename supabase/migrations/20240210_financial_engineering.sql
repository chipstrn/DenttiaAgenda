-- 1. Patient Wallet (Saldo a Favor)
ALTER TABLE public.patients 
ADD COLUMN IF NOT EXISTS wallet_balance DECIMAL(10, 2) DEFAULT 0 NOT NULL;

-- 2. Wallet Transactions (Log of manual top-ups or usage)
CREATE TABLE IF NOT EXISTS public.wallet_transactions (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    patient_id UUID REFERENCES public.patients(id) NOT NULL,
    amount DECIMAL(10, 2) NOT NULL, -- Positive for deposit, Negative for usage
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    created_by UUID REFERENCES auth.users(id),
    clinic_id UUID REFERENCES public.clinics(id)
);

-- Trigger to update patient balance on transaction
CREATE OR REPLACE FUNCTION update_wallet_balance()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE patients 
    SET wallet_balance = wallet_balance + NEW.amount
    WHERE id = NEW.patient_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS update_wallet_balance_trigger ON wallet_transactions;
CREATE TRIGGER update_wallet_balance_trigger
AFTER INSERT ON wallet_transactions
FOR EACH ROW EXECUTE FUNCTION update_wallet_balance();


-- 3. Split Payments Support
-- We need a way to support multiple methods for a SINGLE payment record, OR split the payment record itself.
-- OPTION A: Master Payment + Payment Methods
-- OPTION B: Allow "payments" table to have entries that sum up to the total.

-- We treat 'payments' table as the DEBT/CHARGE generated by an appointment.
-- And 'payment_transactions' as the ACTUAL MONEY received.

CREATE TABLE IF NOT EXISTS public.payment_transactions (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    payment_id UUID REFERENCES public.payments(id) NOT NULL,
    amount DECIMAL(10, 2) NOT NULL,
    method TEXT NOT NULL CHECK (method IN ('cash', 'card', 'transfer', 'wallet')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    notes TEXT,
    clinic_id UUID REFERENCES public.clinics(id)
    -- created_by linked via RLS/Auth
);

-- Trigger to update parent 'payments' status (fully paid vs partial)
CREATE OR REPLACE FUNCTION update_payment_status()
RETURNS TRIGGER AS $$
DECLARE
    v_total_paid DECIMAL(10, 2);
    v_total_amount DECIMAL(10, 2);
BEGIN
    SELECT amount INTO v_total_amount FROM payments WHERE id = NEW.payment_id;
    
    SELECT COALESCE(SUM(amount), 0) INTO v_total_paid 
    FROM payment_transactions 
    WHERE payment_id = NEW.payment_id;

    -- Update parent payment record with amount paid so far
    UPDATE payments 
    SET amount_paid = v_total_paid,
        status = CASE WHEN v_total_paid >= v_total_amount THEN 'completed' ELSE 'partial' END
    WHERE id = NEW.payment_id;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS check_payment_completion ON payment_transactions;
CREATE TRIGGER check_payment_completion
AFTER INSERT ON payment_transactions
FOR EACH ROW EXECUTE FUNCTION update_payment_status();

